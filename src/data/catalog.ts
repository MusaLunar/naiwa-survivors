import type { GameCatalog } from './types.ts';
import manifest from './nailongManifest.json';

function spriteLore(id: string, fallback: string): string {
  const sprites = manifest.sprites as Record<string, { lore?: string }>;
  return sprites[id]?.lore ?? fallback;
}

function medallionLore(id: string, fallback: string): string {
  const medallions = manifest.medallions as Record<string, { lore?: string }>;
  return medallions[id]?.lore ?? fallback;
}

function findGalleryUrl(sourcePath: string, fallback: string): string {
  const found = manifest.gallery.find((g) => g.sourcePath === sourcePath);
  return found?.url ?? fallback;
}

function findGalleryId(sourcePath: string): string | undefined {
  return manifest.gallery.find((g) => g.sourcePath === sourcePath)?.id;
}

